/**
 * build-brand-assets.mjs — generate every shipped icon from one master, so no
 * icon is a hand-edited binary nobody can reproduce.
 *
 *   node apps/web/scripts/build-brand-assets.mjs
 *
 * The master is `apps/web/public/brand/mark.svg` (the twin of the in-app
 * `RishwatMark` component). If the delivered raster artwork is present at
 * `assets/Forest Green R Search Icon.png` it is preferred instead — it carries
 * the illustrated detail the vector cannot — and the illustrations beside it are
 * optimised for the web at the same time. Neither is required: the vector master
 * alone produces a complete icon set, which is why a missing `assets/` folder
 * only prints a note rather than failing the build.
 *
 * Outputs (checked in, regenerated by this script):
 *   apps/web/src/app/icon.png icon1.png icon2.png   favicons (32 / 192 / 512)
 *   apps/web/src/app/apple-icon.png                 iOS home screen (180)
 *   apps/web/public/brand/mark-tile-*.png           raster mark for slides/press
 *   apps/web/public/brand/icon-192.png icon-512.png manifest icons
 *   apps/web/public/brand/icon-maskable-512.png     Android adaptive icon
 *   apps/web/public/brand/illustration-*.webp       optimised illustrations
 *   apps/web/src/app/_brand/mark-data-uri.ts        the mark, inlined for next/og
 */

import { Buffer } from "node:buffer";
import { access, mkdir, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

import sharp from "sharp";

const here = path.dirname(fileURLToPath(import.meta.url));
const webRoot = path.resolve(here, "..");
const repoRoot = path.resolve(webRoot, "../..");
const assets = path.join(repoRoot, "assets");
const appDir = path.join(webRoot, "src/app");
const brandDir = path.join(webRoot, "public/brand");
const brandTsDir = path.join(appDir, "_brand");

/** The official green from DESIGN.md, used to pad the maskable icon. */
const OFFICIAL = "#0b3a20";

const VECTOR_MASTER = path.join(brandDir, "mark.svg");
const RASTER_MASTER = path.join(assets, "Forest Green R Search Icon.png");

const exists = async (file) =>
  access(file).then(
    () => true,
    () => false,
  );

/**
 * The bounding box of the artwork in a raster master: the smallest rectangle
 * containing every pixel that is neither transparent nor within `tolerance` of
 * white. The delivered renders sit on a white canvas with a soft shadow, and an
 * icon built from the whole canvas is a tile floating in white space.
 */
async function artworkBox(file, tolerance = 26) {
  const { data, info } = await sharp(file).ensureAlpha().raw().toBuffer({ resolveWithObject: true });
  const { width, height, channels } = info;
  let top = height;
  let left = width;
  let right = -1;
  let bottom = -1;

  for (let y = 0; y < height; y += 1) {
    for (let x = 0; x < width; x += 1) {
      const i = (y * width + x) * channels;
      if (data[i + 3] < 24) continue;
      const nearWhite =
        255 - data[i] <= tolerance &&
        255 - data[i + 1] <= tolerance &&
        255 - data[i + 2] <= tolerance;
      if (nearWhite) continue;
      if (x < left) left = x;
      if (x > right) right = x;
      if (y < top) top = y;
      if (y > bottom) bottom = y;
    }
  }

  if (right < 0 || bottom < 0) throw new Error(`No artwork found in ${file}`);
  return { left, top, width: right - left + 1, height: bottom - top + 1 };
}

/**
 * A square tile of `size` px. The vector master already carries its own corner
 * radius, so it is only rasterised; a raster master is cropped to its artwork
 * and re-masked, because its corners are rounded *in white* and those show as
 * four bright notches on a dark page.
 */
async function tile(size, { raster }) {
  if (!raster) {
    return sharp(VECTOR_MASTER, { density: 384 })
      .resize(size, size, { fit: "contain", background: { r: 0, g: 0, b: 0, alpha: 0 } })
      .png({ compressionLevel: 9 })
      .toBuffer();
  }

  const box = await artworkBox(RASTER_MASTER);
  // Square the crop about its centre so the R stays optically centred.
  const side = Math.max(box.width, box.height);
  const left = Math.max(0, Math.round(box.left + box.width / 2 - side / 2));
  const top = Math.max(0, Math.round(box.top + box.height / 2 - side / 2));
  const meta = await sharp(RASTER_MASTER).metadata();
  const radius = Math.round(size * 0.225);
  const mask = Buffer.from(
    `<svg xmlns="http://www.w3.org/2000/svg" width="${size}" height="${size}"><rect width="${size}" height="${size}" rx="${radius}" ry="${radius}" fill="#fff"/></svg>`,
  );

  return sharp(RASTER_MASTER)
    .extract({
      left,
      top,
      width: Math.min(side, (meta.width ?? side) - left),
      height: Math.min(side, (meta.height ?? side) - top),
    })
    .resize(size, size, { fit: "cover", kernel: "lanczos3" })
    .ensureAlpha()
    .composite([{ input: mask, blend: "dest-in" }])
    .png({ compressionLevel: 9 })
    .toBuffer();
}

/**
 * The Android adaptive icon: full bleed official green, artwork inset to the
 * safe zone so a launcher that crops to a circle cannot clip the R.
 */
async function maskable(size, options) {
  const art = await tile(Math.round(size * 0.78), options);
  return sharp({ create: { width: size, height: size, channels: 4, background: OFFICIAL } })
    .composite([{ input: art, gravity: "center" }])
    .png({ compressionLevel: 9 })
    .toBuffer();
}

async function write(file, buffer) {
  await mkdir(path.dirname(file), { recursive: true });
  await writeFile(file, buffer);
  console.log(`  ${path.relative(repoRoot, file)}  ${(buffer.length / 1024).toFixed(1)} kB`);
}

/** Illustrations the product uses, when the delivered artwork is present. */
const ILLUSTRATIONS = [
  ["Transparency Search_ No Results Found.png", "illustration-no-results.webp", 960],
  ["Offline Transparency Portal Illustration.png", "illustration-offline.webp", 960],
  ["Open Data for a Transparent India.png", "illustration-open-data.webp", 1200],
  ["Official Fees and Citizen Transparency.png", "illustration-official-vs-reported.webp", 1200],
  ["Neoclassical Capitol with Indian Flag.png", "illustration-capitol.webp", 1400],
];

async function main() {
  const raster = await exists(RASTER_MASTER);
  console.log(
    raster
      ? "Brand assets — from the delivered raster artwork in assets/"
      : "Brand assets — from the vector master public/brand/mark.svg (assets/ not present)",
  );
  const options = { raster };

  // Three real favicon sizes rather than one large PNG the browser downscales to
  // 16px: Next emits each as its own <link rel="icon" sizes>.
  await write(path.join(appDir, "icon.png"), await tile(32, options));
  await write(path.join(appDir, "icon1.png"), await tile(192, options));
  await write(path.join(appDir, "icon2.png"), await tile(512, options));
  // iOS applies its own corner mask to a full-bleed tile.
  await write(path.join(appDir, "apple-icon.png"), await maskable(180, options));

  await write(path.join(brandDir, "icon-192.png"), await tile(192, options));
  await write(path.join(brandDir, "icon-512.png"), await tile(512, options));
  await write(path.join(brandDir, "icon-maskable-512.png"), await maskable(512, options));
  for (const size of [64, 96, 512]) {
    await write(path.join(brandDir, `mark-tile-${size}.png`), await tile(size, options));
  }

  // next/og cannot be relied on to read the filesystem at request time on every
  // host, so the mark travels with the bundle as a data URI.
  const ogMark = await tile(128, options);
  await write(
    path.join(brandTsDir, "mark-data-uri.ts"),
    Buffer.from(
      "// GENERATED by apps/web/scripts/build-brand-assets.mjs — do not edit.\n" +
        "// The 128px brand tile, inlined so `next/og` never needs a network or\n" +
        "// filesystem read while rendering the share card.\n" +
        `export const MARK_DATA_URI =\n  "data:image/png;base64,${ogMark.toString("base64")}";\n`,
      "utf8",
    ),
  );

  if (raster) {
    for (const [source, out, width] of ILLUSTRATIONS) {
      const file = path.join(assets, source);
      if (!(await exists(file))) {
        console.log(`  (skipped ${out}: ${source} not in assets/)`);
        continue;
      }
      await write(
        path.join(brandDir, out),
        await sharp(file).resize({ width, withoutEnlargement: true }).webp({ quality: 82 }).toBuffer(),
      );
    }
  } else {
    console.log("  (skipped illustrations: no assets/ folder)");
  }

  console.log("Done.");
}

main().catch((error) => {
  console.error(error);
  process.exitCode = 1;
});
